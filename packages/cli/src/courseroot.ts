/**
 * Find the directory a course actually lives in, and fail in a way an author can act on.
 *
 * Two things went wrong before this existed: the error named `manifest.json` — the *generated* file, which
 * an author never writes — so it read as "you are missing a file" rather than "you are in the wrong
 * directory"; and it arrived as an unhandled ENOENT stack trace.
 */
import { existsSync, readdirSync, statSync } from 'node:fs';
import { join, relative, resolve } from 'node:path';

const hasManifest = (d: string) => existsSync(join(d, 'manifest.json.in')) || existsSync(join(d, 'manifest.json'));

export function findCourseRoot(given: string): string {
  const dir = resolve(given);

  if (!existsSync(dir)) {
    console.error(`No such file or directory: ${dir}`);
    process.exit(1);
  }
  if (statSync(dir).isFile()) {
    const hint = dir.endsWith('.course')
      ? `That is a built bundle, not a course directory. Try:\n  tome preview ${given}\n  tome unpack ${given} <dir>`
      : 'Point this at the course directory, not a file.';
    console.error(`${given} is a file.\n${hint}`);
    process.exit(1);
  }
  if (hasManifest(dir)) return dir;

  // A zip from an author usually unpacks into a wrapper folder, so the manifest is one level down.
  const nested = readdirSync(dir, { withFileTypes: true })
    .filter((e) => e.isDirectory() && !e.name.startsWith('.') && e.name !== 'node_modules')
    .map((e) => join(dir, e.name))
    .filter(hasManifest);

  if (nested.length === 1) {
    // A path full of ../.. is worse than the absolute one it replaces.
    const rel = relative(process.cwd(), nested[0]);
    const shown = !rel || rel.startsWith('..') ? nested[0] : rel;
    console.log(`Using ${shown} — the course is one level down.\n`);
    return nested[0];
  }
  if (nested.length > 1) {
    console.error(`${dir} contains ${nested.length} courses. Point this at one of them:`);
    for (const n of nested) { const r = relative(process.cwd(), n); console.error(`  ${!r || r.startsWith('..') ? n : r}`); }
    process.exit(1);
  }

  console.error(
    `${dir} is not a course directory: it has no manifest.json.in.\n\n` +
    `A course directory contains manifest.json.in, lessons/ and usually assets/.\n` +
    `  · Wrong directory? Check where you are, or pass the path: tome validate path/to/course\n` +
    `  · Sent a .course file? Use: tome preview file.course   or   tome unpack file.course <dir>\n` +
    `  · Starting from scratch? Use: tome new <dir>\n\n` +
    `(manifest.json is generated by \`tome build\`; you never write it by hand.)`,
  );
  process.exit(1);
}
